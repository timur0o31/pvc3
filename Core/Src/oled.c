/* В HAL адрес сдвинут влево; R/W добавляет сам контроллер I2C.
 * Для SSD1306 control = 0x00 означает команды, 0x40 — пиксели.
 * Здесь MemAddress HAL используется как управляющий байт SSD1306. */
static HAL_StatusTypeDef write_bytes(uint16_t address, uint8_t control,
                                     uint8_t *data, uint16_t size)
{
    return HAL_I2C_Mem_Write(&hi2c1, address, control, I2C_MEMADD_SIZE_8BIT,
                             data, size, TIMEOUT_MS);
}

/* P0 расширителя подключён к активному низким уровнем RESET OLED.
 * Чтение-модификация-запись сохраняет настройки остальных выводов. */
static HAL_StatusTypeDef reset_panel(void)
{
    uint8_t output, config;
    HAL_StatusTypeDef ret;
    ret = HAL_I2C_Mem_Read(&hi2c1, RESET_ADDRESS, 1, I2C_MEMADD_SIZE_8BIT,
                           &output, 1, TIMEOUT_MS);
    if (ret != HAL_OK) return ret;
    ret = HAL_I2C_Mem_Read(&hi2c1, RESET_ADDRESS, 3, I2C_MEMADD_SIZE_8BIT,
                           &config, 1, TIMEOUT_MS);
    if (ret != HAL_OK) return ret;
    output &= (uint8_t)~1u;
    ret = write_bytes(RESET_ADDRESS, 1, &output, 1);
    if (ret != HAL_OK) return ret;
    config &= (uint8_t)~1u; /* 0 = выход. */
    ret = write_bytes(RESET_ADDRESS, 3, &config, 1);
    if (ret != HAL_OK) return ret;
    HAL_Delay(2);
    output |= 1u;
    ret = write_bytes(RESET_ADDRESS, 1, &output, 1);
    HAL_Delay(10);
    return ret;
}

HAL_StatusTypeDef OLED_Init(void)
{
    ready = false;
    pending = false;
    HAL_Delay(100); /* Питание дисплея должно стабилизироваться перед RESET. */
    status = reset_panel();
    if (status != HAL_OK) return status;
    uint8_t commands[] = {
        0xAE,             /* Выключить изображение на время настройки. */
        0x20, 0x02,       /* Page addressing: 8 страниц по 128 байт. */
        0xC8, 0xA1,       /* Направления COM и SEG как в примере стенда. */
        0x40, 0xD3, 0x00, /* Начальная строка и смещение = 0. */
        0xA8, 0x3F,       /* Multiplex: 64 строки. */
        0x81, 0x7F,       /* Контраст. */
        0xA4, 0xA6,       /* Вывод RAM, обычное (не инверсное) изображение. */
        0xD5, 0x80,       /* Тактирование дисплея. */
        0xD9, 0xF1,       /* Предзаряд для внутреннего charge pump. */
        0xDA, 0x12,       /* Разводка COM для панели 128x64. */
        0xDB, 0x20,       /* Уровень VCOMH. */
        0x8D, 0x14,       /* Включить внутренний преобразователь питания. */
        0x2E              /* Отключить прокрутку. */
    };
    status = write_bytes(OLED_ADDRESS, 0, commands, sizeof commands);
    if (status != HAL_OK) return status;
    ready = true;
    OLED_Clear();
    OLED_Present();
    /* Только при старте ждём полный кадр, чтобы не показывать мусор из RAM OLED. */
    while (OLED_Busy()) OLED_Update();
    if (status != HAL_OK) return status;
    uint8_t on = 0xAF;
    status = write_bytes(OLED_ADDRESS, 0, &on, 1);
    ready = status == HAL_OK;
    return status;
}

void OLED_Clear(void)
{
    memset(framebuffer, 0, sizeof framebuffer);
}

/* Один байт содержит вертикальные 8 пикселей одной колонки страницы. */
static void pixel(unsigned x, unsigned y)
{
    if (x < WIDTH && y < HEIGHT)
        framebuffer[x + (y / 8u) * WIDTH] |= (uint8_t)(1u << (y % 8u));
}

void OLED_Text(unsigned x, unsigned y, const char *text, unsigned scale)
{
    if (scale != 1u && scale != 2u) return;
    for (; *text && x + 7u * scale <= WIDTH; text++, x += 7u * scale) {
        unsigned char c = (unsigned char)*text;
        if (c < 32u || c > 126u) c = '?';
        for (unsigned row = 0; row < 10u; row++) {
            uint16_t bits = Font7x10[(c - 32u) * 10u + row];
            for (unsigned col = 0; col < 7u; col++) {
                if ((bits & (0x8000u >> col)) == 0u) continue;
                for (unsigned dy = 0; dy < scale; dy++)
                    for (unsigned dx = 0; dx < scale; dx++)
                        pixel(x + col * scale + dx, y + row * scale + dy);
            }
        }
    }
}

void OLED_Present(void)
{
    if (!ready || pending) return;
    offset = 0;
    page_addressed = false;
    pending = true;
}

bool OLED_Busy(void) { return pending; }
HAL_StatusTypeDef OLED_GetStatus(void) { return status; }

void OLED_Update(void)
{
    if (!pending) return;
    if (!page_addressed) {
        uint8_t commands[] = {(uint8_t)(0xB0u + offset / WIDTH), 0x00, 0x10};
        status = write_bytes(OLED_ADDRESS, 0, commands, sizeof commands);
        page_addressed = true;
    } else {
        /* 4 байта при 100 кГц: около 0.63 мс на транзакцию.
         * Между вызовами main успевает обслужить UART и таймеры замка.
         * Полный кадр за один HAL-вызов задержал бы main более чем на 90 мс. */
        status = write_bytes(OLED_ADDRESS, 0x40, &framebuffer[offset], CHUNK_SIZE);
        offset += CHUNK_SIZE;
        if (offset % WIDTH == 0u) page_addressed = false;
        if (offset == sizeof framebuffer) pending = false;
    }
    if (status != HAL_OK) {
        /* Отсутствие дисплея не останавливает замок и не создаёт бесконечный retry. */
        ready = false;
        pending = false;
    }
}
